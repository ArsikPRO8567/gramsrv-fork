-- Раунд 21: флаг refunded у неулучшенных подарков (savedStarGift.refunded,
-- flags.9 официальной схемы). В Telegram флаг выставляется при возврате
-- средств: платёж за подарок/улучшение отменяется, улучшенный подарок
-- откатывается к исходному (неулучшенному) состоянию, и клиент показывает к
-- такому подарку надпись вида «Улучшение подарка отменено, поскольку поступил
-- запрос на возврат средств…». Сама механика возврата пока не реализована —
-- флаг только подготовлен: столбец создаётся с DEFAULT false, сервер читает
-- его в домен и отдаёт клиентам в savedStarGift.refunded.
--
-- Обратная миграция просто удаляет столбец (значение всегда false, данных нет).

ALTER TABLE public.peer_star_gifts
    ADD COLUMN IF NOT EXISTS refunded boolean NOT NULL DEFAULT false;
