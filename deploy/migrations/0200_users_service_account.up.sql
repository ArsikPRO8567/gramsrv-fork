-- Раунд 45: флаг service_account в таблице users.
--
-- На официальном сервере существуют служебные аккаунты и боты, которым нельзя
-- отправлять подарки: попытка обычного аккаунта отправить подарок, улучшение,
-- передать коллекционный подарок, купить его на маркете или сделать предложение
-- о покупке в адрес такого аккаунта завершается USER_GIFT_UNAVAILABLE, в адрес
-- бота — PEER_ID_INVALID. Существующий флаг support (официальная поддержка)
-- на это ограничение не влияет. Аккаунты и боты с флагом service_account сами
-- лишены этих ограничений и могут свободно отправлять подарки другим служебным
-- аккаунтам и даже ботам.
--
-- Флаг по умолчанию false; выставляется оператором через админ-API
-- (POST /v1/accounts/set-service-account). Встроенные служебные ряды сервера
-- (777000 Telesrv, BotFather, Stickers/Chat/Verify/Verifier bots, premiumbot,
-- gifbot) помечаются сразу: они должны сохранять возможность дарить подарки.
ALTER TABLE public.users ADD COLUMN service_account boolean NOT NULL DEFAULT false;

UPDATE public.users SET service_account = true
WHERE id IN (777000, 93372553, 1063110917, 1250000007, 1250000011, 1250000013, 1250000015, 1250000017);
