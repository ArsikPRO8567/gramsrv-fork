-- Раунд 21: режимы минимальной ставки аукциона и продление раундов при
-- изменении топа.
--
-- star_gift_auctions: три новых столбца.
--   raise_min_bid — режим минимальной ставки. FALSE (по умолчанию): минимальная
--     ставка всего аукциона — несменяемое значение min_bid_amount, сервер не
--     меняет его ни при ставках, ни на границах раундов. TRUE: режим повышения
--     («поведение официальных серверов») — при старте нового раунда и у
--     ожидающего аукциона минимальная ставка = стоимость подарка в ревизии;
--     каждая поставленная ставка (>= текущего минимума) поднимает минимум до
--     «последняя ставка + 1»; по окончании раунда (после выявления победителей)
--     минимум откатывается к стоимости ревизии для следующего раунда.
--   round_extends — индивидуальные настройки продления раундов, jsonb-объект
--     вида {"round_2":{"window":30,"top":3,"threshold":120}}. Для раунда с
--     настройкой: если в последние threshold секунд раунда ставка изменит
--     состав/порядок топ-top участников, сервер прибавляет к оставшемуся
--     времени раунда window секунд (раунд не закончится, пока топ-top
--     продолжает меняться). Пропущенный threshold означает window (официальная
--     анти-снайп семантика). Раунды без настройки не продлеваются. NULL —
--     продления выключены для всего аукциона.
--   round_extend_seconds — служебный счётчик: суммарное продление ТЕКУЩЕГО
--     раунда в секундах. Сбрасывается в 0 при переходе к следующему раунду;
--     нужен, чтобы пересчёт границы раунда в settle не стирал продления,
--     применённые ставками в середине раунда.
-- Столбцы заполняются администратором (psql/внешние инструменты), сервер
-- читает raise_min_bid/round_extends и сам ведёт round_extend_seconds.

ALTER TABLE public.star_gift_auctions
    ADD COLUMN IF NOT EXISTS raise_min_bid        boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS round_extends        jsonb,
    ADD COLUMN IF NOT EXISTS round_extend_seconds integer NOT NULL DEFAULT 0;

-- Ревизии улучшений с нулевой ценой (UpgradeStars = 0) легальны: все подарки
-- такой ревизии улучшаются бесплатно (аукционные подарки с prepaid-флагом).
-- Ограничение upgrade_stars > 0 из 0090 заменяется на >= 0.
ALTER TABLE public.star_gift_collectible_revisions
    DROP CONSTRAINT IF EXISTS star_gift_collectible_price_check,
    ADD CONSTRAINT star_gift_collectible_price_check CHECK (upgrade_stars >= 0);
